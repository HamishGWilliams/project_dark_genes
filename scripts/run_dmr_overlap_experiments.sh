#!/bin/bash
#SBATCH --job-name=dmr_overlap_dark
#SBATCH --mem=8G
#SBATCH --partition=uoa-compute
#SBATCH -N 1
#SBATCH -n 4
#SBATCH --time=04:00:00
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=r02hw22@abdn.ac.uk
#SBATCH --output=/uoa/home/r02hw22/sharedscratch/project_dark_genes/logs/outputs/%x_%j.out
#SBATCH --error=/uoa/home/r02hw22/sharedscratch/project_dark_genes/logs/errors/%x_%j.err

set -euo pipefail

cd /uoa/home/r02hw22/sharedscratch/project_dark_genes

PROJECT_DIR="${PROJECT_DIR:-/uoa/scratch/users/r02hw22/project_dark_genes}"
DMR_DIR="${DMR_DIR:-${PROJECT_DIR}/10_methylation_overlap}"
CANDIDATES="${CANDIDATES:-${PROJECT_DIR}/09_repeat_overlap/equina_dark_candidates.repeat_overlap.tsv}"
OUTDIR="${OUTDIR:-${PROJECT_DIR}/10_methylation_overlap}"

mkdir -p "${PROJECT_DIR}/logs/outputs" "${PROJECT_DIR}/logs/errors" "${OUTDIR}"

if [[ ! -s "${CANDIDATES}" ]]; then
    echo "ERROR: candidate table not found: ${CANDIDATES}" >&2
    exit 1
fi

find_one_dmr() {
    local pattern="$1"
    # Search likely interval files but ignore outputs generated by this workflow.
    find "${DMR_DIR}" -maxdepth 2 -type f \
        \( -iname "*.tsv" -o -iname "*.txt" -o -iname "*.bed" -o -iname "*.csv" \) \
        -iname "*${pattern}*" \
        ! -iname "*dmr_overlap*" \
        ! -iname "*summary*" \
        ! -path "*/exp1_acute_naive_diesel/*" \
        ! -path "*/exp2_primed_acclimated_diesel/*" \
        | sort | head -n 1
}

EXP1_DMR="${EXP1_DMR:-}"
EXP2_DMR="${EXP2_DMR:-}"

if [[ -z "${EXP1_DMR}" ]]; then
    EXP1_DMR="$(find_one_dmr "exp1")"
fi
if [[ -z "${EXP2_DMR}" ]]; then
    EXP2_DMR="$(find_one_dmr "exp2")"
fi

if [[ -z "${EXP1_DMR}" || ! -s "${EXP1_DMR}" ]]; then
    echo "ERROR: could not find exp1 DMR file in ${DMR_DIR}." >&2
    echo "Set EXP1_DMR=/path/to/exp1_dmr_file and rerun." >&2
    exit 1
fi

if [[ -z "${EXP2_DMR}" || ! -s "${EXP2_DMR}" ]]; then
    echo "ERROR: could not find exp2 DMR file in ${DMR_DIR}." >&2
    echo "Set EXP2_DMR=/path/to/exp2_dmr_file and rerun." >&2
    exit 1
fi

echo "Candidate table: ${CANDIDATES}"
echo "Exp1 acute/naive diesel DMRs: ${EXP1_DMR}"
echo "Exp2 primed/acclimated diesel DMRs: ${EXP2_DMR}"

run_overlap() {
    local label="$1"
    local dmr_file="$2"
    local out_subdir="${OUTDIR}/${label}"
    mkdir -p "${out_subdir}"

    echo
    echo "Running DMR overlap for ${label}..."

    python3 scripts/add_dmr_overlap_context.py \
        --candidates "${CANDIDATES}" \
        --dmrs "${dmr_file}" \
        --outdir "${out_subdir}" \
        --prefix "equina_dark_candidates.${label}" \
        --candidate-id-column protein_id \
        --contig-column contig \
        --start-column transcript_start \
        --end-column transcript_end \
        ${DMR_FORMAT:+--dmr-format "${DMR_FORMAT}"} \
        ${DMR_CONTIG_COLUMN:+--dmr-contig-column "${DMR_CONTIG_COLUMN}"} \
        ${DMR_START_COLUMN:+--dmr-start-column "${DMR_START_COLUMN}"} \
        ${DMR_END_COLUMN:+--dmr-end-column "${DMR_END_COLUMN}"} \
        ${DMR_ID_COLUMN:+--dmr-id-column "${DMR_ID_COLUMN}"} \
        ${DMR_EFFECT_COLUMN:+--dmr-effect-column "${DMR_EFFECT_COLUMN}"}

    echo "Summary for ${label}:"
    cat "${out_subdir}/equina_dark_candidates.${label}.dmr_overlap.summary.txt"
}

run_overlap "exp1_acute_naive_diesel" "${EXP1_DMR}"
run_overlap "exp2_primed_acclimated_diesel" "${EXP2_DMR}"

echo
printf "experiment\tsummary_file\toverlap_table\n" > "${OUTDIR}/equina_dark_candidates.dmr_overlap.experiment_manifest.tsv"
printf "exp1_acute_naive_diesel\t%s\t%s\n" \
    "${OUTDIR}/exp1_acute_naive_diesel/equina_dark_candidates.exp1_acute_naive_diesel.dmr_overlap.summary.txt" \
    "${OUTDIR}/exp1_acute_naive_diesel/equina_dark_candidates.exp1_acute_naive_diesel.dmr_overlap.tsv" \
    >> "${OUTDIR}/equina_dark_candidates.dmr_overlap.experiment_manifest.tsv"
printf "exp2_primed_acclimated_diesel\t%s\t%s\n" \
    "${OUTDIR}/exp2_primed_acclimated_diesel/equina_dark_candidates.exp2_primed_acclimated_diesel.dmr_overlap.summary.txt" \
    "${OUTDIR}/exp2_primed_acclimated_diesel/equina_dark_candidates.exp2_primed_acclimated_diesel.dmr_overlap.tsv" \
    >> "${OUTDIR}/equina_dark_candidates.dmr_overlap.experiment_manifest.tsv"

echo
cat "${OUTDIR}/equina_dark_candidates.dmr_overlap.experiment_manifest.tsv"
echo "DMR overlap analyses complete."
